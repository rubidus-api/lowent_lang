// low_smt.h — **SMT 백엔드: 선형 정수 산술의 반박기** (REQ-0004 · 후속 M, 2026-08-05).
//
// ★★★ **왜 이것이 필요한가.** 구간 분석(RFC-0053)은 변수마다 `[lo,hi]` 를 나른다. 그것으로는
//   **변수 사이의 관계**를 표현할 수 없어서, 이 저장소는 필요한 관계를 하나씩 **손으로** 특수
//   경우로 넣어 왔다: 차분 제약(`lerel`), 길이 관계(`lenlt`), 용량 형태(`lenge_p`), 행우선
//   (`lenge_p × lenge_q`). 넷 다 같은 모양의 추론이고, 다섯째가 오면 다섯 번째 특수 경우가 된다.
//   ⇒ **일반 절차로 바꾼다.** 사실을 선형 부등식의 집합으로 적고, 목표의 **부정**을 더한 뒤
//     그 집합이 **모순임을 보인다**(refutation). 모순이면 목표는 참이다.
//
// ★★★★ **그런데 솔버를 믿지 않는다 — 이것이 이 파일의 설계 전부다.**
//
//   SMT 를 붙일 때 이 저장소가 가장 걱정한 것은 *"RFC-0086 의 증명서 체계(파이썬·Coq·추출본)에
//   **네 번째 권위**가 끼어든다"* 였다. 솔버가 *"UNSAT"* 이라고 말하면 그 말을 누가 검산하는가?
//   ⇒ 답: **아무도 그 말을 안 믿는다.** 반박에 성공하면 이 모듈은 **Farkas 계수**를 함께 낸다 —
//     각 제약에 곱할 **음이 아닌 수** λ 로서, 그것들을 곱해 더하면 `0 ≤ 음수` 라는 **산술적
//     모순**이 그 자리에서 나온다. 증명서에 실리는 것은 판정이 아니라 **그 계수들**이고,
//     독립 검증기는 **곱하고 더하기만** 하면 된다(`scripts/check-certificates.py`).
//
//     ☞ 그래서: 솔버는 **찾는 자**(oracle)이고 **권위가 아니다**. 이 구별이
//       ① 부트스트랩(RFC-0078)이 솔버 없이도 **검증**할 수 있게 하고
//       ② 우리가 이 절차를 나중에 통째로 바꿔도 **증명서 형식은 그대로**이게 한다.
//
// ★★ **정직: 이것은 완전한 SMT 솔버가 아니다.** 다루는 이론은 **선형 정수 산술의 논리곱 조각**
//   (QF_LIA 의 conjunctive fragment)이고, 절차는 λ 를 추적하는 **Fourier–Motzkin 소거**다.
//   · 분리(∨)·비선형(곱)·나머지 연산은 **다루지 않는다** — 못 하면 그냥 **안 지운다**(보수적).
//   · 유리수 위에서 모순을 보인다. 유리수에서 모순이면 정수에서도 모순이므로 **건전하다**
//     (역은 아니다 — 그래서 정수라서만 모순인 자리는 **놓친다**. 놓치는 것은 안전하다).
//   ⇒ 이 한계를 적어 두는 이유: *"SMT 를 붙였다"* 가 *"이제 다 증명된다"* 로 반올림되지 않도록.
#ifndef LOW_SMT_H
#define LOW_SMT_H

#include <stdbool.h>
#include "proven/array.h"

// 계의 상한 — 넘으면 **반박을 시도하지 않는다**(보수적으로 검사를 남긴다).
// ★ 상한이 있는 이유는 두 가지다: ① FM 소거는 최악에서 지수로 불어난다
//   ② 증명서 한 줄에 실을 수 있는 수의 개수가 유한하다(사람이 읽고 diff 하는 텍스트다).
#define LOW_SMT_MAXV   6      // 변수(값 슬롯 · 길이)
#define LOW_SMT_MAXC   10     // 제약(사실 + 목표의 부정)
#define LOW_SMT_MAXROW 64     // 소거 도중 살아 있는 행의 상한

// 제약은 전부 **한 모양**이다:  Σ a[v]·x[v] + c ≤ 0.
// ★ 한 모양으로 못박는 것이 이 파일이 짧은 이유다 — 부등호 방향이 둘이면 모든 규칙이 두 벌이 된다.
typedef struct {
    proven_i64 a[LOW_SMT_MAXV];
    proven_i64 c;
} low_smt_row_t;

typedef struct {
    low_smt_row_t row[LOW_SMT_MAXC];
    proven_size_t nc;                 // 제약 수
    proven_size_t nv;                 // 변수 수
} low_smt_sys_t;

void low_smt_init(low_smt_sys_t *s, proven_size_t nv);

// 제약 하나를 더한다. 넘치면 false — **조용히 버리지 않는다**(버리면 계가 거짓이 아니라
// *약해지는* 것이라 건전하긴 하지만, 왜 못 지웠는지 아무도 모르게 된다).
bool low_smt_add(low_smt_sys_t *s, const proven_i64 *a, proven_i64 c);

// ★★★ **반박한다.** 성공하면 lam[0..nc) 에 **음이 아닌 정수 계수**를 채운다:
//        Σ lam[j]·row[j] 가 (계수 전부 0, 상수 > 0) 이 되어  0 ≤ -(양수)  라는 모순이 된다.
//   ⇒ 즉 이 계는 **만족 불가능**이고, 목표의 부정을 넣었다면 목표는 참이다.
//   실패하면 false — 모른다는 뜻이지 거짓이라는 뜻이 아니다(그래서 호출자는 검사를 남긴다).
bool low_smt_refute(const low_smt_sys_t *s, proven_i64 *lam);

// 계 + 계수를 받아 **모순을 다시 계산한다** — 컴파일러 자신이 쓰는 자기 검산.
// ★ 증명서를 내기 전에 **여기서 한 번 더 본다**: 검증기가 나중에 잡을 거짓말을 그 자리에서 막는다.
bool low_smt_check(const low_smt_sys_t *s, const proven_i64 *lam);

#endif // LOW_SMT_H
