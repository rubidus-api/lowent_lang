// low_version.h — **버전은 한 곳에서만 온다.**
//
// ★ 두 곳에 적힌 숫자는 반드시 어긋난다(이 저장소가 여러 번 겪은 일이다: 풀 크기·게이트 수·
//   effect 원자 수). 그래서 도구가 말하는 버전, 문서가 적는 버전, 릴리스 태그가 **같은 문자열**
//   이어야 하고, 그것을 게이트가 대조한다(`check-docs-fresh`).
//
// v1.0.0 — 2026-08-01. 기준은 RFC-0088 안 다(게이트 축 + 임베디드 floor 프로그램 하나 +
//          "v1이 약속하지 않는 것"), 판정은 `scripts/check-v1.py`, 선언은 소유자.
//          ☞ v1 은 **완성이 아니라 기준 통과**다. 무엇을 약속하지 않는지는 SPEC-015 §16.4.2.
#ifndef LOW_VERSION_H
#define LOW_VERSION_H

#define LOW_VERSION "1.6.0"

// ★★★ **"버전" 은 한 낱말이 아니라 네 축이다** (RFC-0089 R4 · 단계 E, 2026-08-03).
//
//   `v1.0.0` 은 이 저장소 안에서 *"RFC-0088 의 증거 기준을 통과했다"* 는 뜻인데, **밖에서는
//   호환성 약속으로 읽힌다.** 한 낱말이 네 가지를 뜻하면 셋은 거짓말이 된다 — 그리고 그 거짓말은
//   남이 우리 ABI 를 고정된 것으로 믿고 링크할 때 **그 사람의 빌드에서** 터진다.
//
//   ⇒ 네 축을 **각자 이름 붙이고, 도구가 그것을 말한다**(`--version`):
//     ① 릴리스(lowentc)     — 이 도구의 판. RFC-0088 증거 기준 통과를 뜻한다(완성이 아니다).
//     ② 언어 개정          — 표면·의미의 개정. 키워드/빌트인이 바뀌면 이것이 움직인다.
//     ③ 호환성 epoch       — ABI/API 를 **언제 얼렸나**. 2026-08-05 에 **잠정으로 열었다**.
//     ④ 성숙도             — experimental / stable-core / freestanding-verified 중 어디인가.
//
//   ☞ ③은 2026-08-04 까지 `none` 이었고 **그때는 그것이 가장 정직한 칸이었다**: 열지 않은 것을
//     열었다고 적으면 그것이 곧 지킬 수 없는 약속이다. 여는 조건은 **RFC-0089 §8-1**(①표면 목록
//     ②변경 게이트 ③두 판 사이 실측 ④소유자 선언)이고, ①②③은 `scripts/check-abi.py` 가 **매
//     실행마다 다시 세운다**(후속 G). ④는 2026-08-05 에 소유자가 했다 — **잠정으로**.
// ★★★ **epoch 를 잠정으로 열었다** (2026-08-05 · 소유자 선언).
//
//   `epoch` 의 원뜻은 *"시대"* 가 아니라 **시간을 재기 시작하는 한 점**이다(Unix epoch 가 그
//   뜻 그대로다 — 1970-01-01 은 시대가 아니라 **원점**이다). 호환성에 그 낱말을 쓰는 이유도
//   같다: *"우리는 ABI 를 안 깬다"* 는 문장은 **언제부터인가**가 없으면 뜻이 없다.
//   ⇒ epoch 는 **호환성을 재기 시작하는 눈금 0** 이고, 그래서 값이 **날짜**다.
//
//   ☞ 그리고 이 저장소는 그 눈금을 **지금** 놓을 자격이 있다 — 조건 ①②③이 서 있기 때문이다
//     (RFC-0089 §8-1: ①표면 목록 ②변경 게이트 ③구판 헤더 × 신판 오브젝트 실측).
//     ④ 선언이 남아 있었고, 그것을 2026-08-05 에 소유자가 했다.
//
// ★★ **`provisional`(잠정)이 무엇을 뜻하는가** — 이 낱말이 이 파일에서 가장 중요한 낱말이다.
//
//     오늘 약속하는 것:  **조용히 바뀌지 않는다.** 표면은 `docs/abi-surface.h` 에 기록돼 있고,
//                       바뀌면 `check-abi` 가 **빨간불**이 된다. 바뀐다면 그것은 announced 다.
//     아직 아닌 것:      **안 바뀐다.** 언어가 개발 중이므로 표면은 **여전히 바뀔 수 있다.**
//
//   ⇒ 즉 이 축은 이제 `none`(아무 약속 없음)과 frozen(안 바뀜) **사이**에 있고, 그 중간을
//     이름으로 부른다. 중간을 이름으로 안 부르면 사람들은 **둘 중 하나로 반올림한다** —
//     그리고 반올림은 언제나 **자기에게 유리한 쪽**으로 일어난다(= 얼었다고 읽는다).
//   ★ 그러니 이 상태를 **도구가 말해야 한다**(`--version`)와 **헤더가 스스로 적어야 한다**
//     (`--emit-h` 의 첫 줄). 남이 우리 헤더를 볼 때, 그 종이 자신이 어느 눈금의 것인지 말한다.
//
// ★★★ 상태가 `frozen` 이 되는 날 **게이트의 뜻이 바뀐다**: 잠정에서는 `check-abi --write` 로
//   표면을 옮길 수 있지만(의도를 커밋에 적는 조건으로), frozen 에서는 그 문이 **닫힌다** —
//   `check-abi.py` 가 그 규칙을 강제한다. 상태를 낱말 하나 고치는 것이 곧 규율을 바꾼다.
#define LOW_RELEASE      LOW_VERSION          /* ① lowentc 릴리스 */
#define LOW_LANG_REV     "1.6"                /* ② 언어 개정(표면·의미) — 1.6: 태그 없는 `note` 거절 · `neg` 는 부호 있는 타입만이고 넘치면 멈춘다(RFC-0052 D4) · `mut` 없는 `for` 원소에 `set` 거절 — v1.6.0 */
// ★ 1.3 → 1.4 (2026-10-03, 소유자 결정 RFC-0127 «ⓐⓑⓒ» · RFC-0113 §7b): 표면이 깨지는 방향의 변경이 여럿 들어왔다 —
//   비트셋·레인 op 접두사(`bitset_*`·`lane_*`) · 파일·그물 잎은 `call_builtin` 뒤 · `<식> . do` 와 한 폼 몸 거절 · `.name` 폐기 ·
//   `not is_some` → `is_none` · `proc` 의 `effects` 필수 · `bitset_insert` 와 값 버리는 문장 거절 · 아무것도 안 닫는 점 거절.
//   옛 철자는 동의어로 남지 않는다(진단이 새 철자를 댄다). epoch 는 여전히 provisional — 이 줄이 그 알림이다.
// ★ 1.1 → 1.2 (2026-09-25, X-0052 ⓐ 소유자 결정): `end`·`do` 바로 뒤의 점이 이제 안 선다
//   (`E-DOT-STRAY`). `end` 가 블록과 그 폼을 함께 닫으므로 그 점은 닫을 것이 없었고, 처리기가
//   빈 폼으로 조용히 버리고 있었다. 표면이 깨지는 방향이라 이 축이 움직인다(epoch 는 여전히 provisional).
// ★ 1.0 → 1.1 (2026-09-24): 빌트인이 196 → 201 이 됐고, 계산 잎 열다섯이
//   `call_builtin <이름>` 뒤로 내려갔다(RFC-0125). **맨몸 호출은 이제 안 선다**
//   (`E-BUILTIN-BARE`) — 표면이 깨지는 방향이다. 이 축의 규칙이 «키워드/빌트인이
//   바뀌면 움직인다» 이므로 움직인다. ☞ epoch 가 아직 `provisional` 이라 이 깨짐은
//   약속 위반이 아니다 — 「조용히 바뀌지 않는다」만 약속했고, 이렇게 적는 것이 그 약속이다.
// ★ epoch 2026-08-05 → 2026-09-29 (RFC-0134, 소유자 결정): C 로 내보내는 이름이 전부 바뀌었다 — 맨 op 이름 대신
//   경로와 길이(`lw_7listlit_6inside`). 맨 이름은 C 예약어·표준 헤더·런타임과 부딪쳐 네이티브 빌드를 깨뜨렸다(X-0078).
//   원점을 옮겨 알린다 — `provisional` 은 «조용히 바뀌지 않는다» 만 약속했고, 이것이 그 알림이다.
#define LOW_ABI_EPOCH        "2026-09-29"     /* ③ 호환성 epoch — **원점(날짜)** */
#define LOW_ABI_EPOCH_STATUS "provisional"    /*    그 눈금의 성격: 잠정 / frozen */
#define LOW_MATURITY     "freestanding-verified"  /* ④ 성숙도(stable-core 아님) */

#endif
